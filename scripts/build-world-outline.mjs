// One-off dev script: converts the world-atlas land-110m topojson into a
// compact array of [lat, lng] polylines embedded as src/worldOutline.ts.
// Not part of the published build output — run manually, then delete
// the topojson-client devDependency.
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync("/tmp/land-110m.json", "utf8"));
const geo = feature(topo, topo.objects.land);

function round(n) {
  return Math.round(n * 10) / 10;
}

const lines = [];
for (const feat of geo.features) {
  const polygons =
    feat.geometry.type === "Polygon" ? [feat.geometry.coordinates] : feat.geometry.coordinates;
  for (const poly of polygons) {
    for (const ring of poly) {
      // Full point density from the 110m dataset — small islands (Japan, UK,
      // etc.) already have few vertices at this resolution, so further
      // decimation visibly distorts them.
      lines.push(ring.map(([lng, lat]) => [round(lat), round(lng)]));
    }
  }
}

const out = `// Auto-generated by scripts/build-world-outline.mjs from the world-atlas
// land-110m dataset (Natural Earth, public domain). Do not edit by hand.
export const WORLD_OUTLINE: [number, number][][] = ${JSON.stringify(lines)};
`;

writeFileSync("src/worldOutline.ts", out);
console.log(`Wrote ${lines.length} polylines`);
